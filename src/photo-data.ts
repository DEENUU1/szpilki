function plate(
  rows: readonly Row[],
  page: number,
  modelId: string,
  region: "upper" | "lower",
  source: string,
): PhotoPin[] {
  return rows.map(
    (
      [x, y, pl, en, latin, recognizeEn, recognizePl, theoryEn, theoryPl],
      index,
    ) => ({
      id: `mcminn-${page}-${index}`,
      atlasId: mcminnId,
      page,
      x: x / 1274,
      y: y / 1800,
      crop:
        page === 295
          ? { x: 0.014, y: 0.173, w: 0.88, h: 0.484 }
          : { x: 0.029, y: 0.105, w: 0.88, h: page === 121 ? 0.62 : 0.73 },
      pl,
      en,
      latin,
      region,
      system: "skeletal",
      exercise: 2,
      recognize: { en: recognizeEn, pl: recognizePl },
      theory: { en: theoryEn, pl: theoryPl },
      modelId,
      source,
    }),
  );
}
