export function polishName(organ: Organ): string | null {
  const base = organ.organ_id.replace(/_[lr]$/, "");
  let name = names[base];
  if (!name) {
    const m = /^(cervical|thoracic|lumbar)_vertebra_(\d+)$/.exec(base);
    if (m)
      name = `Kręg ${m[1] === "cervical" ? "szyjny C" : m[1] === "thoracic" ? "piersiowy Th" : "lędźwiowy L"}${m[2]}`;
  }
  if (!name) return null;
  return (
    name +
    (/_l$/.test(organ.organ_id)
      ? " · lewa strona"
      : /_r$/.test(organ.organ_id)
        ? " · prawa strona"
        : "")
  );
}
export function displayName(organ: Organ): string {
  return getLanguage() === "en"
    ? organ.name_en
    : (polishName(organ) ?? organ.ta2_latin);
}
export function acceptedNames(organ: Organ): string[] {
  return [
    polishName(organ) ?? "",
    (polishName(organ) ?? "").replace(/ · (lewa|prawa) strona$/, ""),
    organ.ta2_latin,
    organ.name_en,
    organ.name_en.replace(/ \((left|right)\)$/, ""),
    displayName(organ),
    displayName(organ).replace(/ · (lewa|prawa) strona$/, ""),
  ];
}
